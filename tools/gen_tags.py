"""Generate Data.lua (mountID -> tags) from a ZoneMount SavedVariables export.

usage: python tools/gen_tags.py path/to/ZoneMount.lua [curated.json]

Rules come straight from Tags.lua so Lua and Python can't drift apart.
curated.json: { "<mountID>": "tag tag ~weak", ... } -- hand fixes that replace the derived tags.
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
lua = (ROOT / "Tags.lua").read_text(encoding="utf8")

rules = {}
for m in re.finditer(r'^    (\w+)\s*= \{(.*?)\},?\s*$', lua, re.M):
    words = re.findall(r'"([^"]+)"', m.group(2))
    if m.group(1) in ("flying",) or words:
        rules.setdefault(m.group(1), []).extend(words)
rules = {k: v for k, v in rules.items() if k not in ("function",)}
safe = set(re.search(r'for t in \((.*?)\):gmatch', lua, re.S).group(1).replace('"', "").replace("..", " ").split())
type_tags = {231: "sea", 232: "sea", 254: "sea"}

def norm(s):
    return " " + re.sub(r"[^\w']", " ", s.lower(), flags=re.A) + " "

def has(n, word):
    w = re.sub(r"[^\w']", " ", word.lower(), flags=re.A)
    return (" " + w + " " in n) if len(w) < 4 else (" " + w in n)

def parse_export(path):
    s = pathlib.Path(path).read_text(encoding="utf8")
    out = []
    for blk in re.findall(r'\n\{\n(.*?)\n\},', s, re.S):
        d = {}
        for k, v in re.findall(r'\["(\w+)"\] = (.*?),?\n', blk + "\n"):
            v = v.strip(); d[k] = v[1:-1] if v.startswith('"') else v
        if "id" in d:
            out.append(dict(id=int(d["id"]), name=d["name"].replace('\\"', '"'),
                            type=int(d.get("type", 0)), desc=d.get("desc", ""), owned=d.get("owned") == "true"))
    return out

def derive(e):
    nn, nd = norm(e["name"]), norm(e["desc"])
    strong, weak = [], []
    for tag, words in rules.items():
        if any(has(nn, w) for w in words): strong.append(tag)
        elif tag in safe and any(has(nd, w) for w in words): weak.append(tag)
    t = type_tags.get(e["type"])
    if t and t not in strong and t not in weak: weak.append(t)
    return sorted(strong), sorted(weak)

def fmt(strong, weak):
    return " ".join(strong + ["~" + w for w in weak])

if __name__ == "__main__":
    ents = parse_export(sys.argv[1])
    curated = json.loads(pathlib.Path(sys.argv[2]).read_text(encoding="utf8")) if len(sys.argv) > 2 else {}
    rows, untagged = [], []
    for e in sorted(ents, key=lambda e: e["id"]):
        if "test mount" in e["name"].lower():
            continue
        c = curated.get(str(e["id"]), curated.get(e["name"]))
        tags = c if c is not None else fmt(*derive(e))
        if not tags: untagged.append(e["name"])
        else: rows.append(f'    [{e["id"]}] = "{tags}", -- {e["name"].replace(chr(10), " ")}')
    header = "-- GENERATED by tools/gen_tags.py -- do not edit by hand (put fixes in tools/curated.json).\nlocal _, ns = ...\nns.mountTags = {\n"
    (ROOT / "Data.lua").write_text(header + "\n".join(rows) + "\n}\n", encoding="utf8")
    print(f"{len(rows)} tagged, {len(untagged)} untagged")
    (ROOT / "tools" / "untagged.txt").write_text("\n".join(untagged), encoding="utf8")
